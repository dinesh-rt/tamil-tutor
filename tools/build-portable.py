#!/usr/bin/env python3
"""Build a portable, fully-offline copy of தமிழ் Tutor — no server, no internet, ever.

    python3 tools/build-portable.py              # dist/portable/  + a .zip of it
    python3 tools/build-portable.py --single     # dist/tamil-tutor-offline.html
    python3 tools/build-portable.py --single --no-audio

**Folder build** (recommended — keeps the recordings):
    dist/portable/index.html     the app, CSS and JS already inlined
    dist/portable/audio/…        the voice clips + pack-index.js
    → double-click index.html. Works from a USB stick, a school PC, an email.

**Single-file build** (`--single`) squeezes the recordings *inside* one .html as
base64, so there is literally one file to carry (~23 MB). Clips are decoded
lazily into Blob URLs, so it only pays for what it plays.

Everything else — progress, stars, custom words — lives in that browser's
localStorage. On a machine you don't own, use the grown-up corner's Export
before you leave; on your own machine it just remembers.

No dependencies. Reuses tools/build-single-file.py so all builds stay identical.
"""
import base64
import importlib.util
import json
import os
import shutil
import time
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "dist")
AUDIO = os.path.join(ROOT, "audio")

# load the bundler as a module and share its inliner
_spec = importlib.util.spec_from_file_location("bsf", os.path.join(ROOT, "tools", "build-single-file.py"))
bsf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bsf)


def human(n):
    return "%.1f MB" % (n / 1048576) if n > 1048576 else "%.0f KB" % (n / 1024)


SW_TEMPLATE = '''/* Generated by tools/build-portable.py — offline-first for the portable build.
   Everything is served from the cache once seen; there is no server to go back to. */
var CACHE = 'tamil-tutor-portable-%s';   /* stamped per build */
var SHELL = %s;

self.addEventListener('install', function (e) {
  e.waitUntil((async function () {
    var c = await caches.open(CACHE);
    await Promise.all(SHELL.map(function (u) {
      return fetch(u).then(function (r) { return (r && r.ok) ? c.put(u, r) : null; }).catch(function () { return null; });
    }));
    return self.skipWaiting();
  })());
});

self.addEventListener('activate', function (e) {
  e.waitUntil((async function () {
    var keys = await caches.keys();
    await Promise.all(keys.map(function (k) { return k === CACHE ? null : caches.delete(k); }));
    return self.clients.claim();
  })());
});

self.addEventListener('message', function (e) {
  if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  /* voice clips: cache forever, and let a missing one fail quietly so the app
     can fall back to the device voice */
  if (url.pathname.indexOf('/audio/') >= 0 && !/manifest\\.json$|pack-index\\.js$/.test(url.pathname)) {
    e.respondWith(caches.match(req).then(function (hit) {
      return hit || fetch(req).then(function (res) {
        if (res && res.ok) { var copy = res.clone(); caches.open(CACHE).then(function (c) { c.put(req, copy); }); }
        return res;
      }).catch(function () { return new Response('', { status: 503 }); });
    }));
    return;
  }

  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(function (res) {
      var copy = res.clone(); caches.open(CACHE).then(function (c) { c.put(req, copy); });
      return res;
    }).catch(function () {
      return caches.match(req).then(function (hit) { return hit || caches.match('index.html'); });
    }));
    return;
  }

  e.respondWith(caches.match(req).then(function (hit) {
    if (hit) {                       // serve instantly, refresh in the background
      fetch(req).then(function (res) {
        if (res && res.ok) { var copy = res.clone(); caches.open(CACHE).then(function (c) { c.put(req, copy); }); }
      }).catch(function () { });
      return hit;
    }
    return fetch(req).then(function (res) {
      if (res && res.ok) { var copy = res.clone(); caches.open(CACHE).then(function (c) { c.put(req, copy); }); }
      return res;
    });
  }));
});
'''


def ensure_pack_index():
    """audio/pack-index.js sets window.TT_AUDIO_PACK — fetch() is blocked on
    file://, so the folder build needs the list handed over by a <script>."""
    man = os.path.join(AUDIO, "manifest.json")
    if not os.path.exists(man):
        return None
    with open(man, encoding="utf-8") as fh:
        data = json.load(fh)
    js = ("/* generated by tools/build-portable.py — tells the app which recordings "
          "exist when fetch() is not allowed (file://). */\nwindow.TT_AUDIO_PACK = "
          + json.dumps({"version": 1, "voices": data.get("voices", {}), "files": data["files"]},
                       ensure_ascii=False, separators=(",", ":"))
          + ";\n")
    with open(os.path.join(AUDIO, "pack-index.js"), "w", encoding="utf-8") as fh:
        fh.write(js)
    return data


def ensure_story_pack_index():
    """audio/books/pack-index.js sets window.TT_STORY_PACK.

    Under file:// the app cannot fetch audio/books/manifest.json, so in the
    offline folder the ten stories would sit unlistened-to beside their own
    recordings. The voice pack solved exactly this with a generated script
    tag; the story index does the same thing. Never copied to the hosted
    site — over http the app reads the manifest itself, and a stale baked-in
    copy is how silent books get shipped.
    """
    src = os.path.join(AUDIO, "books", "manifest.json")
    if not os.path.exists(src):
        return None
    with open(src, encoding="utf-8") as fh:
        data = fh.read()
    out = os.path.join(AUDIO, "books", "pack-index.js")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("/* generated by tools/build-portable.py — the story index for file:// */\n"
                 "window.TT_STORY_PACK = " + data.strip() + ";\n")
    return out


def copy_tree(src, dst):
    n = 0
    for dirpath, _, files in os.walk(src):
        rel = os.path.relpath(dirpath, src)
        out = os.path.join(dst, rel)
        os.makedirs(out, exist_ok=True)
        for f in files:
            shutil.copy2(os.path.join(dirpath, f), os.path.join(out, f))
            n += 1
    return n


def dir_size(path):
    return sum(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(path) for f in fs)


def write_pwa(outdir):
    """Copy the manifest + icons and generate a service worker so the folder is
    installable when it is served over http(s). Double-clicking still works —
    the app only registers a worker on http(s)."""
    shutil.copy2(os.path.join(ROOT, "manifest.webmanifest"), os.path.join(outdir, "manifest.webmanifest"))
    n = copy_tree(os.path.join(ROOT, "icons"), os.path.join(outdir, "icons"))
    icons = ["icons/" + f for f in sorted(os.listdir(os.path.join(ROOT, "icons")))]
    shell = ["./", "index.html", "manifest.webmanifest", "audio/pack-index.js"] + icons
    with open(os.path.join(outdir, "sw.js"), "w", encoding="utf-8") as fh:
        fh.write(SW_TEMPLATE % (time.strftime("%Y.%m.%d"), json.dumps(shell)))
    return n


def build_folder(outdir=None, zip_it=True, pwa=True):
    outdir = outdir or os.path.join(DIST, "portable")
    data = ensure_pack_index()
    clips = sum(len(v) for v in data["files"].values()) if data else 0
    words = len(data["files"]) if data else 0

    if os.path.isdir(outdir):
        shutil.rmtree(outdir)
    os.makedirs(outdir, exist_ok=True)

    head = '<script src="audio/pack-index.js"></script>' if data else ""
    if ensure_story_pack_index():
        head += '<script src="audio/books/pack-index.js"></script>'
    html, _js = bsf.build_html(head, keep_pwa=pwa)
    with open(os.path.join(outdir, "index.html"), "w", encoding="utf-8") as fh:
        fh.write(html)

    pwa_icons = write_pwa(outdir) if pwa else 0

    copied = copy_tree(AUDIO, os.path.join(outdir, "audio")) if data else 0

    # covers, and only covers: the raw renders beside them are 20× the weight
    # of the pictures the app actually points at
    art = 0
    srcdir = os.path.join(ROOT, "images", "books")
    if os.path.isdir(srcdir):
        dst = os.path.join(outdir, "images", "books")
        os.makedirs(dst, exist_ok=True)
        for f in sorted(os.listdir(srcdir)):
            if f.endswith(".webp"):
                shutil.copy2(os.path.join(srcdir, f), os.path.join(dst, f))
                art += 1

    note = "\n".join([
        "தமிழ் Tutor — offline copy",
        "==========================",
        "",
        "Double-click  index.html  — that's the whole app. No server, no internet.",
        "",
        "Recordings : %s" % ("%d clips for %d words — they play from the audio folder beside this file" % (clips, words) if data
                             else "none — make them with  python3 tools/make-voice-pack.py  then rebuild"),
        "",
        "Progress, stars and your own words are saved inside the web browser you",
        "open this with. To move to another computer: open the app → 🧩 grown-up",
        "corner → Data → Export, take the JSON file with you and Restore it there.",
        "",
        "Tip: in Chrome/Edge you can also open index.html and use it as it is;",
        "installing (Add to Home Screen) only works when it is served over http(s).",
    ])
    with open(os.path.join(outdir, "OPEN-ME.txt"), "w", encoding="utf-8") as fh:
        fh.write(note + "\n")

    print("\nportable folder → %s" % os.path.relpath(outdir, ROOT))
    print("  index.html  %s" % human(os.path.getsize(os.path.join(outdir, "index.html"))))
    if pwa:
        print("  PWA         manifest.webmanifest + sw.js + %d icons → installable when served" % pwa_icons)
    print("  audio       %d files, %s" % (copied, human(dir_size(os.path.join(outdir, "audio"))) if copied else "—"))
    print("  recordings  %d clips / %d words" % (clips, words))

    if zip_it:
        zpath = os.path.join(DIST, "tamil-tutor-portable.zip")
        if os.path.exists(zpath):
            os.remove(zpath)
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for dirpath, _, files in os.walk(outdir):
                for f in files:
                    full = os.path.join(dirpath, f)
                    z.write(full, os.path.relpath(full, outdir))
        print("  zip         %s  (%s)" % (os.path.relpath(zpath, ROOT), human(os.path.getsize(zpath))))
    return outdir


def build_single(embed_audio=True):
    out = os.path.join(DIST, "tamil-tutor-offline.html")
    os.makedirs(DIST, exist_ok=True)
    head = ""
    data = ensure_pack_index() if os.path.exists(os.path.join(AUDIO, "manifest.json")) else None

    if embed_audio and data:
        parts, missing = [], 0
        for wid, kinds in data["files"].items():
            for kind in kinds:
                rel = os.path.join("ta", "say") if kind == "say" else kind
                p = os.path.join(AUDIO, rel, wid.replace("/", "__") + ".mp3")
                if not os.path.exists(p):
                    missing += 1
                    continue
                with open(p, "rb") as fh:
                    parts.append("%s\t%s\t%s" % (wid, kind, base64.b64encode(fh.read()).decode("ascii")))
        index = json.dumps({"version": 1, "voices": data.get("voices", {}), "files": data["files"]},
                           ensure_ascii=False, separators=(",", ":"))
        head = ('<script type="application/json" id="tt-audio-index">%s</script>\n'
                '<script type="text/plain" id="tt-audio-pack">%s</script>' % (index, "\n".join(parts)))
        print("\nembedding %d clips (%d missing)" % (len(parts), missing))
    elif embed_audio:
        print("\nno audio/ folder — building without recordings")

    html, js = bsf.build_html(head)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(html)
    print("single file   → %s  (%s, js %s)" % (os.path.relpath(out, ROOT), human(os.path.getsize(out)), human(js)))
    print("double-click it — one file, everything inside, works with the Wi-Fi off")
    return out


def main():
    args = sys.argv[1:]
    if "--single" in args:
        build_single(embed_audio="--no-audio" not in args)
    else:
        build_folder(zip_it="--no-zip" not in args, pwa="--no-pwa" not in args)
        print("\nnow: dist/portable/index.html opens with no server at all")
        print("and  npm run share  serves it for Add to Home Screen on your phone")
        print("or share dist/tamil-tutor-portable.zip — unzip and double-click")


if __name__ == "__main__":
    main()
